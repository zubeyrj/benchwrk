// Bundles content/seed and content/seedx into api/_content.js, which the owner's
// "Load course content" button sends to the database. Run after editing course files.
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = {};
for (const f of fs.readdirSync(path.join(root, "content/seed")).sort()) out["content/" + f.replace(/\.json$/, "")] = JSON.parse(fs.readFileSync(path.join(root, "content/seed", f), "utf8"));
for (const f of fs.readdirSync(path.join(root, "content/seedx")).sort()) { const d = JSON.parse(fs.readFileSync(path.join(root, "content/seedx", f), "utf8")); out["lessons/" + d.id] = d; }
fs.writeFileSync(path.join(root, "api/_content.js"), "// Generated by scripts/gen-content.mjs. Do not edit by hand.\nexport const CONTENT = " + JSON.stringify(out) + ";\n");
console.log("content: " + Object.keys(out).length + " documents");
